"""Generate synthetic filesystem trees for swath-local benchmarks.

Trees (under --base, default $BENCH_DATA):
  wide       1,000,000 empty files in 1,000 directories (1,000 per directory).
  deep       500,000 empty files: a fan-out-4 directory tree of depth 8 whose first
             12,500 leaves (enumeration order) each hold 40 files. A full 4^8 tree
             would have 65,536 leaves, which cannot hold ~40 files/leaf at 500k files,
             so only the leaves needed are materialised (ancestors created on demand).
  realistic  ~1,000,000 files: project-like trees (src/, nested node_modules/, .git/objects/),
             dated Hive-style data partitions, and a home-like documents area with spaces,
             non-ASCII (valid UTF-8) names and a few symlinks. Files are sparse
             (ftruncate to a pseudo-random size) so st_size is realistic but disk use is
             near zero.
  huge       200,000 empty files in ONE directory (tests splitting a large directory's stat phase).
             Not generated by default.

Deterministic (fixed seed). Re-running on an existing tree is refused unless --force.
"""
import argparse
import os
import random
import shutil
import sys
import time


def touch(path, size=0):
    fd = os.open(path, os.O_CREAT | os.O_WRONLY | os.O_TRUNC, 0o644)
    if size:
        os.ftruncate(fd, size)
    os.close(fd)


def gen_wide(root):
    n = 0
    for d in range(1000):
        dp = os.path.join(root, f"dir-{d:04d}")
        os.mkdir(dp)
        for f in range(1000):
            touch(os.path.join(dp, f"file-{f:04d}.dat"))
            n += 1
    return n


def gen_deep(root, depth=8, fanout=4, leaves=12500, per_leaf=40):
    n = 0
    made = set()
    for leaf in range(leaves):
        digits = []
        x = leaf
        for _ in range(depth):
            digits.append(x % fanout)
            x //= fanout
        digits.reverse()
        path = root
        for level, dgt in enumerate(digits):
            path = os.path.join(path, f"d{level}-{dgt}")
            if path not in made:
                os.mkdir(path)
                made.add(path)
        for f in range(per_leaf):
            touch(os.path.join(path, f"f{f:02d}.txt"))
            n += 1
    return n


WORDS = ("alpha beta gamma delta core util http json model view render parse codec "
         "stream buffer index cache store queue event user auth token config server "
         "client router handler schema table query plan merge sort").split()
EXTS = [".js", ".ts", ".go", ".py", ".java", ".json", ".md", ".css", ".html", ".yml"]
UNICODE = ["café", "naïve", "résumé", "日本語", "Привет", "straße", "emoji-🙂", "ñandú"]


def rsize(rng, scale):
    # log-uniform sizes: many small, few large
    return int(10 ** rng.uniform(1, scale))


def gen_project(rng, root, name, n_src, n_nm_pkgs):
    n = 0
    p = os.path.join(root, name)
    os.mkdir(p)
    for f in ("README.md", "package.json", "LICENSE", ".gitignore", "Makefile"):
        touch(os.path.join(p, f), rsize(rng, 4)); n += 1
    # src: nested packages, depth 2-5
    src = os.path.join(p, "src")
    os.mkdir(src)
    dirs = [src]
    while sum(1 for _ in dirs) < max(4, n_src // 25):
        parent = rng.choice(dirs)
        if parent.count(os.sep) - src.count(os.sep) >= 5:
            continue
        d = os.path.join(parent, rng.choice(WORDS) + str(rng.randrange(100)))
        if not os.path.exists(d):
            os.mkdir(d); dirs.append(d)
    for i in range(n_src):
        d = rng.choice(dirs)
        f = os.path.join(d, f"{rng.choice(WORDS)}_{i}{rng.choice(EXTS)}")
        touch(f, rsize(rng, 5)); n += 1
    # node_modules: packages with nested node_modules (deep small files)
    nm = os.path.join(p, "node_modules")
    os.mkdir(nm)

    def pkg(base, depth):
        nonlocal n
        pk = os.path.join(base, f"{rng.choice(WORDS)}-{rng.choice(WORDS)}-{rng.randrange(10**4)}")
        if os.path.exists(pk):
            return
        os.mkdir(pk)
        touch(os.path.join(pk, "package.json"), rsize(rng, 3)); n += 1
        touch(os.path.join(pk, "index.js"), rsize(rng, 4)); n += 1
        lib = os.path.join(pk, "lib")
        os.mkdir(lib)
        for j in range(rng.randrange(5, 25)):
            touch(os.path.join(lib, f"{rng.choice(WORDS)}{j}.js"), rsize(rng, 4)); n += 1
        if depth < 4 and rng.random() < 0.35:
            sub = os.path.join(pk, "node_modules")
            os.mkdir(sub)
            for _ in range(rng.randrange(1, 4)):
                pkg(sub, depth + 1)

    for _ in range(n_nm_pkgs):
        pkg(nm, 0)
    # .git objects: 256 fan-out dirs
    obj = os.path.join(p, ".git", "objects")
    os.makedirs(obj)
    for h in range(256):
        os.mkdir(os.path.join(obj, f"{h:02x}"))
    for _ in range(n_src // 2):
        h = rng.getrandbits(160)
        hx = f"{h:040x}"
        touch(os.path.join(obj, hx[:2], hx[2:]), rsize(rng, 4)); n += 1
    os.symlink("README.md", os.path.join(p, "README.link"))
    n += 1
    return n


def gen_realistic(root):
    rng = random.Random(20261105)
    n = 0
    projects = os.path.join(root, "projects")
    os.mkdir(projects)
    for i in range(40):
        n += gen_project(rng, projects, f"proj-{i:02d}-{rng.choice(WORDS)}", 4000, 300)
    # dated partitions
    import datetime
    data = os.path.join(root, "data", "events")
    os.makedirs(data)
    day = datetime.date(2025, 1, 1)
    for _ in range(300):
        for hour in range(24):
            d = os.path.join(data, f"year={day.year}", f"month={day.month:02d}", f"day={day.day:02d}", f"hour={hour:02d}")
            os.makedirs(d)
            for k in range(20):
                touch(os.path.join(d, f"part-{k:05d}-{rng.getrandbits(32):08x}.snappy.parquet"), rsize(rng, 8)); n += 1
        day += datetime.timedelta(days=1)
    # home-like documents
    home = os.path.join(root, "home")
    os.mkdir(home)
    for u in range(20):
        ud = os.path.join(home, f"user{u}")
        for sub in ("Documents", "Photos/2024", "Photos/2025", "Music/Some Artist", "Downloads"):
            os.makedirs(os.path.join(ud, sub))
        for k in range(2500):
            sub = rng.choice(("Documents", "Photos/2024", "Photos/2025", "Music/Some Artist", "Downloads"))
            nm = f"{rng.choice(UNICODE)} {rng.choice(WORDS)} ({k}).{rng.choice(['pdf','jpg','mp3','docx','txt'])}"
            touch(os.path.join(ud, sub, nm), rsize(rng, 7)); n += 1
        os.symlink("Documents", os.path.join(ud, "docs-link"))
        os.symlink("/nonexistent/target", os.path.join(ud, "dangling"))
        n += 2
    return n


def gen_huge(root):
    d = os.path.join(root, "one-dir")
    os.mkdir(d)
    n = int(os.environ.get("HUGE_FILES", "200000"))
    for f in range(n):
        touch(os.path.join(d, f"entry-{f:07d}"))
    return n


GENS = {"wide": gen_wide, "deep": gen_deep, "realistic": gen_realistic, "huge": gen_huge}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("trees", nargs="*", default=["wide", "deep", "realistic"])
    ap.add_argument("--base", default=os.environ.get("BENCH_DATA", "bench-data"))
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    for t in a.trees:
        root = os.path.join(a.base, t)
        if os.path.exists(root):
            if not a.force:
                print(f"{root} exists; skipping (use --force)", file=sys.stderr)
                continue
            shutil.rmtree(root)
        os.makedirs(root)
        t0 = time.time()
        n = GENS[t](root)
        print(f"{t}: {n} non-directory entries in {time.time()-t0:.1f}s", flush=True)


if __name__ == "__main__":
    main()
